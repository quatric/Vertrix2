#!/usr/bin/env python3
"""The launcher's text font (launcher/font.c): FOT-Rodin NTLG Pro Bold drawn as 8-bit coverage
bitmaps at 16 and 32 pixels (the launcher's text scales 1 and 2), for ASCII and Latin-1 and a
play triangle at code 0x0e:

    make_font.py FONT.otf OUT.c

Needs Pillow. Run it again only to change the font; the output is in the repository."""
import sys

from PIL import Image, ImageDraw, ImageFont

SIZES = (16, 32)
CODES = [0x0E] + list(range(32, 127)) + list(range(0xA0, 0x100))


def glyph(font, size, code):
    if code == 0x0E:
        h = size * 5 // 8
        w = h * 3 // 4
        big = Image.new('L', (w * 4, h * 4), 0)
        ImageDraw.Draw(big).polygon([(0, 0), (w * 4 - 1, h * 2), (0, h * 4 - 1)], fill=255)
        image = big.resize((w, h), Image.LANCZOS)
        return image, 1, (size - h) // 2 - size * 13 // 16, w + size // 4
    ch = chr(code)
    advance = round(font.getlength(ch))
    left, top, right, bottom = font.getbbox(ch, anchor='ls')
    if right <= left or bottom <= top:
        return None, 0, 0, advance
    image = Image.new('L', (right - left, bottom - top), 0)
    ImageDraw.Draw(image).text((-left, -top), ch, font=font, fill=255, anchor='ls')
    return image, left, top, advance


def main():
    font_path, out = sys.argv[1:3]
    lines = ['/* The launcher\'s text font: FOT-Rodin NTLG Pro Bold as coverage bitmaps at 16 and 32',
             ' * pixels (launcher/font.h), generated by tools/make_font.py. Do not edit. */',
             '#include "font.h"', '']
    for scale, size in enumerate(SIZES, 1):
        font = ImageFont.truetype(font_path, size)
        baseline = size * 13 // 16
        data, entries = [], []
        for code in CODES:
            image, left, top, advance = glyph(font, size, code)
            if image is None:
                entries.append((code, 0, 0, 0, 0, advance, len(data)))
                continue
            w, h = image.size
            entries.append((code, w, h, left, baseline + top, advance, len(data)))
            data.extend(image.tobytes())
        lines.append('static const uint8_t pixels%d[%d] = {' % (scale, len(data)))
        for i in range(0, len(data), 24):
            lines.append('    ' + ', '.join('0x%02x' % v for v in data[i:i + 24]) + ',')
        lines.append('};')
        lines.append('')
        lines.append('static const FontGlyph glyphs%d[%d] = {' % (scale, len(entries)))
        for code, w, h, x, y, advance, offset in entries:
            lines.append('    {%d, %d, %d, %d, %d, %d, %d},  /* 0x%02x */' %
                         (code, w, h, x, y, advance, offset, code))
        lines.append('};')
        lines.append('')
    lines.append('const FontSet font_sets[2] = {')
    for scale, size in enumerate(SIZES, 1):
        lines.append('    {%d, %d, glyphs%d, %d, pixels%d},' %
                     (size, size * 13 // 16, scale, len(CODES), scale))
    lines.append('};')
    with open(out, 'w') as f:
        f.write('\n'.join(lines) + '\n')


main()
