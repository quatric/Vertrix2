"""Generate source/lift_imports.[ch]: the original's import slots and their names, so the host
runtime can serve the Win32 calls that reach its boundary by name."""
from pathlib import Path

import pefile

ROOT = Path(__file__).resolve().parents[1]
pe = pefile.PE(str(ROOT / 'Vertrix2.exe'))
base = pe.OPTIONAL_HEADER.ImageBase
rows = []
for entry in pe.DIRECTORY_ENTRY_IMPORT:
    for imp in entry.imports:
        if imp.name:
            rows.append((imp.address, imp.name.decode()))
rows.sort()
(ROOT / 'source' / 'lift_imports.h').write_text('''#ifndef VERTRIX_LIFT_IMPORTS_H
#define VERTRIX_LIFT_IMPORTS_H
#include <stdint.h>

/* The name of the original's import at an import address slot (or at the `jmp [slot]` thunk that
 * forwards to it), or NULL. Generated by tools/gen_imports.py. */
const char *vertrix_import_name(uint32_t address);

/* The import slot a thunk `jmp [slot]` at `address` forwards to, else `address`. */
uint32_t vertrix_import_slot(const uint8_t *image, uint32_t base, uint32_t address);
#endif
''')
body = ['/* Generated by tools/gen_imports.py. */', '#include "lift_imports.h"', '',
        '#include <stddef.h>', '', 'static const struct', '{', '    uint32_t slot;', '    const char *name;',
        '} imports[] = {']
body += ['    {0x%x, "%s"},' % row for row in rows]
body += ['};', '',
         'const char *vertrix_import_name(uint32_t address)', '{', '    size_t low = 0, high = sizeof imports / sizeof imports[0];',
         '    while (low < high)', '    {', '        size_t mid = (low + high) / 2;',
         '        if (imports[mid].slot == address)', '        {', '            return imports[mid].name;', '        }',
         '        if (imports[mid].slot < address)', '        {', '            low = mid + 1;', '        }',
         '        else', '        {', '            high = mid;', '        }', '    }', '    return NULL;', '}', '',
         'uint32_t vertrix_import_slot(const uint8_t *image, uint32_t base, uint32_t address)', '{',
         '    const uint8_t *code;', '    if (address < base + 0xf0000u || address >= base + 0xf1000u)', '    {',
         '        return address;', '    }', '    code = image + (address - base);',
         '    if (code[0] == 0xff && code[1] == 0x25)', '    {',
         '        return (uint32_t)code[2] | (uint32_t)code[3] << 8 | (uint32_t)code[4] << 16 |',
         '               (uint32_t)code[5] << 24;', '    }', '    return address;', '}', '']
(ROOT / 'source' / 'lift_imports.c').write_text('\n'.join(body))
print(len(rows), 'imports')
