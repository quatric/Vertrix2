"""Recover the original partial-block resource measurement table."""
import argparse
from pathlib import Path
from original import Original

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("executable", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--advances", type=Path)
    args = parser.parse_args()
    original = Original(args.executable)
    original.call(0x4B9050)
    data = bytes(original.cpu.mem_read(0x5C1B00, 256))
    rows = ["    {" + ", ".join(str(value) for value in data[i:i + 16]) + "},"
            for i in range(0, 256, 16)]
    args.output.write_text("/* Generated by original 0x4b9050; table at 0x5c1b00. */\n"
                           "static const uint8_t resource_remainder[16][16] =\n{\n"
                           + "\n".join(rows) + "\n};\n")

    if args.advances:
        data = bytes(original.cpu.mem_read(0x5C2000, 15 * 1024))
        rows = []
        for mode in range(15):
            rows.append("{")
            for offset in range(0, 1024, 32):
                chunk = data[mode * 1024 + offset:mode * 1024 + offset + 32]
                rows.append(", ".join(str(value) for value in chunk) + ",")
            rows.append("},")
        args.advances.write_text("/* Original 0x4b9050; modes 1..15 at 0x5c2000. */\n"
            "#ifndef VERTRIX_SCALE_TABLES_H\n#define VERTRIX_SCALE_TABLES_H\n"
            "#include <stdint.h>\nstatic const uint8_t scale_advances[15][1024] = {\n" +
            "\n".join(rows) + "\n};\n#endif\n")

if __name__ == "__main__":
    main()
