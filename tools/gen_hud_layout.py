"""Generate source/hud_layout.c from the original game HUD builder.

The routine at 0x46b810 creates every damier piece of the game screen through 0x471100: the
position comes from the table at 0x4f8880.., the frame from 0x4fbf28.. and the filter item is the
call's ecx.  The routine is executed unchanged in the oracle with the allocator (0x4ca000), the
actor constructors (0x4abd70, 0x4b6350), the chain insert (0x4b5e70) and the box setter (0x4b65d0,
three stack arguments) stubbed; each created actor then holds its position (+0xe, +0x16), damier
frame (+0xb8) and the filter item that 0x4123d0 applied.  The two name boxes are not damier pieces:
they are built by 0x4b6350 / 0x4adf20 / 0x4b65d0 and only styled by items 32 and 33.  The output is the exact creation (= draw)
order.  The characters chosen by the two players ([0x532a68], [0x532a6c]) only change the bonus
slot grid (frames 16/17 after the first 44 pieces); the pieces before and after it are fixed.
"""

import struct
import sys
from pathlib import Path

from unicorn import UC_HOOK_CODE
from unicorn.x86_const import (
    UC_X86_REG_EAX,
    UC_X86_REG_EBX,
    UC_X86_REG_ECX,
    UC_X86_REG_EDX,
    UC_X86_REG_EIP,
    UC_X86_REG_ESP,
)

from original import Original

BUILDER = 0x46B810
FILTER = 0xD00000
STUBBED = {0x4CA000, 0x4ABD70, 0x4B5E70, 0x4B6350, 0x4B65D0}
CHARACTERS = 18
PREFIX = 44
SLOT_FRAMES = (16, 17)
SECOND_SIDE_X = 320


def run(executable, first, second):
    oracle = Original(executable)
    cpu = oracle.cpu
    cpu.mem_map(0x900000, 0x400000)
    cpu.mem_map(FILTER, 0x10000)
    cpu.mem_write(FILTER + 0x5CC, struct.pack("<122I", *([1] * 122)))
    cpu.mem_write(0x532A68, struct.pack("<I", first))
    cpu.mem_write(0x532A6C, struct.pack("<I", second))
    bump = [0x900000]
    created = []
    items = {}
    boxes = []
    box_actors = set()

    def hook(uc, address, size, context):
        if address == 0x4123D0:
            items[uc.reg_read(UC_X86_REG_EBX)] = uc.reg_read(UC_X86_REG_EDX)
        if not (BUILDER <= address < 0x46C5D0 or 0x471100 <= address < 0x471200):
            return
        code = bytes(uc.mem_read(address, 5))
        if code[0] != 0xE8:
            return
        target = (address + 5 + struct.unpack("<i", code[1:])[0]) & 0xFFFFFFFF
        if target not in STUBBED:
            return
        if target == 0x4CA000:
            created.append(bump[0])
            uc.reg_write(UC_X86_REG_EAX, bump[0])
            bump[0] += 0x800
        if target == 0x4B6350:
            box_actors.add(uc.reg_read(UC_X86_REG_EAX))
        if target == 0x4B65D0:
            esp = uc.reg_read(UC_X86_REG_ESP)
            stack = struct.unpack("<3i", bytes(uc.mem_read(esp, 12)))
            boxes.append((uc.reg_read(UC_X86_REG_ECX), stack))
            uc.reg_write(UC_X86_REG_ESP, esp + 12)
        uc.reg_write(UC_X86_REG_EIP, address + 5)

    cpu.hook_add(UC_HOOK_CODE, hook)
    oracle.call(BUILDER, eax=FILTER, edx=0xFFFFFFFF)
    pieces = []
    for actor in created:
        if actor not in items or actor in box_actors:
            continue
        raw = bytes(cpu.mem_read(actor, 0x1C0))
        pieces.append(
            (
                struct.unpack_from("<h", raw, 0xE)[0],
                struct.unpack_from("<h", raw, 0x16)[0],
                struct.unpack_from("<I", raw, 0xB8)[0],
                items[actor],
            )
        )
    return pieces, boxes


def split(pieces):
    end = PREFIX
    while end < len(pieces) and pieces[end][2] in SLOT_FRAMES:
        end += 1
    return pieces[:PREFIX], pieces[PREFIX:end], pieces[end:]


def table(lines, name, pieces):
    lines.append("static const VertrixHudPiece %s[] = {" % name)
    for x, y, frame, item in pieces:
        lines.append("    {%d, %d, %d, %d}," % (x, y, frame, item))
    lines.append("};")


def main(executable, output):
    base, boxes = run(executable, 0, 0)
    prefix, _, tail = split(base)
    sides = [[], []]
    for character in range(CHARACTERS):
        for side, pair in enumerate(((character, 0), (0, character))):
            pieces, _ = run(executable, *pair)
            before, slots, after = split(pieces)
            assert before == prefix and after == tail
            sides[side].append(
                [p for p in slots if (p[0] >= SECOND_SIDE_X) == bool(side)]
            )
    for first, second in ((3, 9), (17, 5), (6, 2)):
        pieces, _ = run(executable, first, second)
        slots = split(pieces)[1]
        mine = sides[0][first] + sides[1][second]
        assert sorted(slots) == sorted(mine), (first, second)
    lines = [
        '#include "hud_layout.h"',
        "",
        "/* Generated by tools/gen_hud_layout.py from the original builder 0x46b810. */",
    ]
    table(lines, "PREFIX", prefix)
    table(lines, "TAIL", tail)
    for side in range(2):
        for character in range(CHARACTERS):
            table(lines, "SLOTS_%d_%d" % (side, character), sides[side][character])
        lines.append("static const VertrixHudSegment SLOTS_%d[%d] = {" % (side, CHARACTERS))
        for character in range(CHARACTERS):
            name = "SLOTS_%d_%d" % (side, character)
            lines.append("    {%s, sizeof %s / sizeof %s[0]}," % (name, name, name))
        lines.append("};")
    lines += [
        "",
        "const VertrixHudLayout VERTRIX_HUD_LAYOUT = {",
        "    {PREFIX, sizeof PREFIX / sizeof PREFIX[0]},",
        "    {TAIL, sizeof TAIL / sizeof TAIL[0]},",
        "    {SLOTS_0, SLOTS_1},",
        "    {%s}," % ", ".join("{%d, %d, %d, %d}" % (c, s[1], s[0], s[2]) for c, s in boxes),
        "};",
    ]
    Path(output).write_text("\n".join(lines) + "\n")
    print(len(prefix), len(tail), boxes)


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
