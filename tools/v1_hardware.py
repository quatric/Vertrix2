"""List every hardware access of the original Vertrix (VERTRIX.EXE): each `in`, `out`, `int`,
`cli` and `sti` in the functions vertrix1/recomp.py discovers, by address, under the Watcom
debug name of the routine that holds it. The port of an `in`/`out` through dx is the last
`mov dx, imm` before it in the routine (shown as `dx` when there is none, a computed port).

usage: v1_hardware.py VERTRIX_EXE [--out docs/v1-hardware-accesses.txt]
"""
import argparse
import bisect
import importlib.util
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / 'vertrix1'))
_spec = importlib.util.spec_from_file_location('vertrix1_recomp', ROOT / 'vertrix1' / 'recomp.py')
v1 = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(v1)

ACCESSES = ('in', 'out', 'int', 'cli', 'sti')


def port_of(ins, before):
    """The port an in/out names: its immediate, or the last constant moved into dx."""
    operands = [o.strip() for o in ins.op_str.split(',')]
    port_operand = operands[1] if ins.mnemonic == 'in' else operands[0]
    if port_operand not in ('dx', 'edx'):
        return port_operand
    for previous in reversed(before):
        target, _, value = previous.op_str.partition(',')
        if target.strip() in ('dx', 'edx', 'dl'):
            value = value.strip()
            if previous.mnemonic == 'mov' and value.startswith('0x') and target.strip() != 'dl':
                return value
            return 'dx'
    return 'dx'


def service_of(ins, before):
    """An int's function number: the last constant moved into ah, ax or eax."""
    for previous in reversed(before[-8:]):
        target, _, value = previous.op_str.partition(',')
        if previous.mnemonic == 'mov' and target.strip() in ('ah', 'ax', 'eax'):
            return '%s=%s' % (target.strip(), value.strip())
    return ''


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('exe')
    parser.add_argument('--out', type=Path)
    args = parser.parse_args()
    p = v1.LEProgram(args.exe)
    funcs, _ = v1.discover(p)
    symbols = sorted((a, n) for a, n in p.symbols.items() if p.in_code(a))
    starts = [a for a, _ in symbols]

    def routine(a):
        i = bisect.bisect_right(starts, a) - 1
        return symbols[i] if i >= 0 else (0, '?')

    rows = defaultdict(dict)
    for f in funcs.values():
        ordered = sorted((a, i) for a, i in f.insns.items() if i is not None)
        for k, (a, ins) in enumerate(ordered):
            if ins.mnemonic not in ACCESSES:
                continue
            before = [i for _, i in ordered[max(0, k - 16):k]]
            if ins.mnemonic in ('in', 'out'):
                what = 'port ' + port_of(ins, before)
            elif ins.mnemonic == 'int':
                what = ('int %s %s' % (ins.op_str, service_of(ins, before))).strip()
            else:
                what = ''
            rows[routine(a)][a] = '%06x  %-4s %-14s %s' % (a, ins.mnemonic, ins.op_str, what)
    lines = ['# Hardware accesses of VERTRIX.EXE (sha256 %s), by routine.' % p.sha256,
             '# Generated by tools/v1_hardware.py.', '']
    for (start, name), found in sorted(rows.items()):
        module = p.symbol_module.get(start, '') if hasattr(p, 'symbol_module') else ''
        lines.append('%s  %06x  %s' % (name, start, module))
        lines += ['    ' + found[a].rstrip() for a in sorted(found)]
    text = '\n'.join(lines) + '\n'
    if args.out:
        args.out.write_text(text)
    else:
        sys.stdout.write(text)


if __name__ == '__main__':
    main()
