"""Compare every signed PCM8 volume-table entry with original 0x40c7d0."""
import argparse
import ctypes
import json
import struct
import subprocess
from pathlib import Path
from original import Original

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("executable", type=Path)
    parser.add_argument("--build-dir", type=Path, required=True)
    args = parser.parse_args()
    build = args.build_dir.resolve()
    build.mkdir(parents=True, exist_ok=True)
    source = Path(__file__).resolve().parents[1] / "source"
    library = build / "mixer-table.dylib"
    subprocess.run(["cc", "-std=c11", "-Wall", "-Wextra", "-Werror", "-shared", "-fPIC", str(source / "mixer.c"), "-o", str(library)], check=True)
    native = ctypes.CDLL(str(library))
    native.vertrix_mixer_pcm8_value.argtypes = [ctypes.c_uint8, ctypes.c_uint32, ctypes.c_uint32, ctypes.c_int, ctypes.POINTER(ctypes.c_int32)]
    original = Original(args.executable)
    original.cpu.mem_map(0x900000, 0x20000)
    original.cpu.mem_map(0x920000, 0x10000)
    for address, value in ((0x52FC2C, 1), (0x52F910, 0x900000), (0x52F914, 0x920000)):
        original.cpu.mem_write(address, struct.pack("<I", value))
    result = ctypes.c_int32()
    result_pointer = ctypes.byref(result)
    cases = 0
    for stereo in (0, 1):
        original.cpu.mem_write(0x52FC1D, bytes([stereo]))
        for master in range(257):
            assert original.call(0x40C7D0, eax=1, edx=master) == 0
            table = struct.unpack("<16640i", original.cpu.mem_read(0x900000, 16640 * 4))
            for index, expected in enumerate(table):
                row, sample = divmod(index, 256)
                assert native.vertrix_mixer_pcm8_value(sample, row, master, stereo, result_pointer)
                assert result.value == expected, (stereo, master, row, sample, result.value, expected)
                cases += 1
    for row, master in ((65, 256), (64, 257), (0xffffffff, 0), (0, 0xffffffff)):
        result.value = 123
        assert not native.vertrix_mixer_pcm8_value(128, row, master, 1, result_pointer)
        assert result.value == 123
    assert not native.vertrix_mixer_pcm8_value(128, 64, 256, 1, None)
    report = {"status": "passed", "table_entries": cases, "original_table_initializations": 514, "scope": "Every entry generated by complete original 0x40c7d0: all 256 PCM8 bit patterns, 65 rows, 257 master gains, mono and stereo. Excludes auxiliary byte table, interpolation, accumulation and output conversion."}
    (build / "mixer-table-verification.json").write_text(json.dumps(report, indent=2) + "\n")
    print(json.dumps(report, indent=2))

if __name__ == "__main__":
    main()
